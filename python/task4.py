import random

# Список всех 16 булевых функций от 2 аргументов с их именами
boolean_functions = {
    "Конъюнкция" : [0, 0, 0, 1],
    "Дизъюнкция" : [0, 1, 1, 1],
    "Сложение" : [0, 1, 1, 0],
    "Штрих Шеффера" : [1, 1, 1, 0],
    "Стрелка Пирса" : [1, 0, 0, 0],
    "Импликация" : [1, 1, 0, 1],
    "Эквивалентность" : [1, 0, 0, 1],
    "Коимплекация" : [0, 0, 1, 0],
    "Обратная имплекация" : [1, 0, 1, 1],
    "Обратная коиплекация" : [0, 1, 0, 0],
    "Функция 0" : [0, 0, 0, 0],
    "Функция переменная x2" : [0, 1, 0, 1],
    "Функция переменная x1" : [0, 0, 1, 1],
    "Функция отрицания x2 (¬x2)" : [1, 0, 1, 0],
    "Функция отрицания x1 (¬x1)" : [1, 1, 0, 0],
    "Функция 1" : [1, 1, 1, 1],
}

def generate_random_function():
    """
    Генерирует случайную булеву функцию от 2 аргументов.
    :return: Кортеж (имя функции, вектор функции).
    """
    name, vector = random.choice(list(boolean_functions.items()))
    return name, vector

def main():
    print("Добро пожаловать в игру 'Узнай имя функции от 2 аргументов'!")
    print("Система предложит вектор функции. Выберите её имя из списка.")

    # Генерация случайной функции
    correct_name, function_vector = generate_random_function()
    print(f"\nВектор функции: {function_vector}")

    # Вывод списка возможных имён функций
    print("\nВыберите имя функции:")
    for i, name in enumerate(boolean_functions.keys(), 1):
        print(f"{i}. {name}")

    # Ввод выбора пользователя
    while True:
        try:
            choice = int(input("Введите номер функции: "))
            if 1 <= choice <= len(boolean_functions):
                break
            else:
                print("Ошибка: введите число от 1 до 16.")
        except ValueError:
            print("Ошибка: введите число.")

    # Получение выбранного имени
    user_choice = list(boolean_functions.keys())[choice - 1]

    # Проверка правильности выбора
    if user_choice == correct_name:
        print(f"Поздравляем! Вы правильно выбрали функцию: {correct_name}.")
    else:
        print(f"К сожалению, вы ошиблись. Правильный ответ: {correct_name}.")

if __name__ == "__main__":
    main()
